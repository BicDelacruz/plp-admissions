-- Phase 3: remember me. One row per remembered browser (selector + hashed validator).
CREATE TABLE IF NOT EXISTS remember_tokens (
    id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    integer      NOT NULL,
    selector   varchar(24)  NOT NULL,
    token_hash varchar(64)  NOT NULL,
    expires_at timestamp(0) NOT NULL,
    created_at timestamp(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_remember_user
        FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_remember_tokens_selector ON remember_tokens (selector);
CREATE INDEX IF NOT EXISTS idx_remember_tokens_user_id ON remember_tokens (user_id);
ALTER TABLE remember_tokens ENABLE ROW LEVEL SECURITY;
