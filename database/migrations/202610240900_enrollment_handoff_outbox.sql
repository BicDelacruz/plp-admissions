-- Admissions -> Enrollment handoff. One row per applicant whose accepted
-- result has been confirmed, tracking whether it reached the enrollment system.
-- The payload is rebuilt from live data on every send, so a retry is never stale.
CREATE TABLE IF NOT EXISTS enrollment_handoff_outbox (
    id                  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    applicant_id        integer      NOT NULL,
    applicant_reference varchar(20)  DEFAULT NULL,
    status              text         NOT NULL DEFAULT 'pending'
                        CHECK (status IN ('pending','sent')),
    attempts            integer      NOT NULL DEFAULT 0,
    last_error          text         DEFAULT NULL,
    last_attempt_at     timestamp(0) DEFAULT NULL,
    sent_at             timestamp(0) DEFAULT NULL,
    created_at          timestamp(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          timestamp(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_handoff_outbox_applicant UNIQUE (applicant_id),
    CONSTRAINT fk_handoff_outbox_applicant
        FOREIGN KEY (applicant_id) REFERENCES applicants (id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_handoff_outbox_status ON enrollment_handoff_outbox (status);
DROP TRIGGER IF EXISTS trg_handoff_outbox_updated_at ON enrollment_handoff_outbox;
CREATE TRIGGER trg_handoff_outbox_updated_at BEFORE UPDATE ON enrollment_handoff_outbox
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();
ALTER TABLE enrollment_handoff_outbox ENABLE ROW LEVEL SECURITY;
